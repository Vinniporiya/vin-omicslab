import type { ContentStatus } from '../../data/schema';
import type { QcStatus } from '../../lib/qc';
import { Badge } from '../ui/Badge';

export const DemoStamp = ({ label = 'Simulated data' }: { label?: string }) => <Badge tone="sim" title="Generated by a seeded simulator. Not real data.">{label}</Badge>;

const CS: Record<ContentStatus, { tone: 'placeholder' | 'draft' | 'verified'; text: string }> = {
  placeholder: { tone: 'placeholder', text: 'Awaiting author input' },
  draft: { tone: 'draft', text: 'Draft, to be confirmed' },
  verified: { tone: 'verified', text: 'Verified' },
};
export const ContentBadge = ({ status }: { status: ContentStatus }) => <Badge tone={CS[status].tone}>{CS[status].text}</Badge>;

export function StatusPill({ status }: { status: QcStatus }) {
  const cls = status === 'PASS' ? 'pass' : status === 'WARNING' ? 'warn' : status === 'FAILED' ? 'fail' : 'review';
  const glyph = status === 'PASS' ? '\u2713' : status === 'WARNING' ? '!' : status === 'FAILED' ? '\u00d7' : '?';
  return <span className={`pill pill-${cls}`}><span aria-hidden="true">{glyph}</span> {status}</span>;
}
