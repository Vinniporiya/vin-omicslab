import type { OmicsDataset } from '../data/dataset';
import type { AnalysisPlan } from './agent/planner';
import { assessReproducibility } from './reproducibility';
import { EVIDENCE_LEVELS } from './evidence';
import { fmtNum, fmtP } from './format';
import type { RunResult } from './run';
import { worst } from './qc';

/** Markdown report assembled only from recorded run values and stated rules. No free-text generation. */
export function buildReport(ds: OmicsDataset, run: RunResult, plan: AnalysisPlan | null): string {
  const p = run.params, label = ds.cellTypes.find((c) => c.id === p.typeId)!.label;
  const repro = assessReproducibility(run.provenance);
  const L: string[] = [];
  L.push(`# Analysis report: pseudobulk differential expression in ${label}`, '');
  L.push('> SIMULATED DEMONSTRATION. The dataset is generated by a seeded simulator. No value below is a real result.', '');
  L.push('## Question', plan ? plan.userQuestion : 'Which genes differ between disease and control within the selected cell type?', '');
  L.push('## Data', `- Dataset: ${ds.meta.title} (${ds.meta.id}), fingerprint ${ds.meta.fingerprint}`, `- ${ds.donors.length} donors (4 control, 4 disease), ${ds.meta.nCells} cells`, '');
  L.push('## Method', '- Counts summed per donor within the cell type, converted to log2 CPM', '- Welch t-test per gene with donors as replicates; Benjamini-Hochberg across tested genes', '- Over-representation of eight gene sets (hypergeometric), hits at nominal P < 0.05', '');
  L.push('## Parameters', ...Object.entries(p).map(([k, v]) => `- ${k}: ${v}`), '');
  L.push('## Quality review', `Overall: ${worst(run.qc)}`, ...run.qc.map((c) => `- ${c.status}: ${c.label} (${c.value})`), '');
  const sig = run.de.rows.filter((r) => r.padj < p.fdr && Math.abs(r.log2fc) >= p.lfc);
  L.push('## Results', `- ${sig.length} of ${run.de.genesTested} genes pass adjusted P < ${p.fdr} and |log2FC| >= ${p.lfc}`, '', '| Gene | log2FC | P | Adjusted P |', '|---|---|---|---|', ...run.de.rows.slice(0, 10).map((r) => `| ${r.gene} | ${fmtNum(r.log2fc)} | ${fmtP(r.p)} | ${fmtP(r.padj)} |`), '');
  L.push('## Interpretation, by evidence level');
  for (const c of run.claims) {
    L.push(`### ${c.statement}`);
    for (const l of EVIDENCE_LEVELS) L.push(`- **${l.label}:** ${c.layers[l.level]?.text ?? 'none attached'}`);
    L.push('');
  }
  L.push('## Limitations', '- Simulated data; effects assigned at random to synthetic gene IDs', '- Demo statistics stand in for edgeR, DESeq2 or limma-voom', '- Checks marked REQUIRES REVIEW were not performed', '');
  L.push('## Reproducibility', `Status: ${repro.status}`, ...repro.items.map((i) => `- [${i.present ? 'x' : ' '}] ${i.label}`), '', `Run ${run.id}; result hash ${run.resultHash}; ${run.provenance.createdAt}`);
  return L.join('\n');
}
